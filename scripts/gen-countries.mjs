// Generates src/lib/data/countries.ts from the world-countries package.
const NL = String.fromCharCode(10);
import wc from 'world-countries';
import fs from 'node:fs';

const rows = wc
  .filter((c) => c.cca2 && typeof c.area === 'number' && c.area > 0)
  .map((c) => ({
    code: c.cca2,
    name: c.name.common,
    areaKm2: c.area,
    flagUrl: 'https://flagcdn.com/' + c.cca2.toLowerCase() + '.svg',
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

// Size normalization: size = (ln(area) + OFFSET) / overallScale,
// with OFFSET chosen so that the largest and smallest countries differ by
// exactly a factor of 2 (max = 2 * min), e.g. Russia 17.1M km2 vs Vatican 0.44 km2.
const maxA = Math.max(...rows.map((r) => r.areaKm2));
const minA = Math.min(...rows.map((r) => r.areaKm2));
const OFFSET = Math.log(maxA) - 2 * Math.log(minA);

const J = (v) => JSON.stringify(v);
const entries = rows
  .map(
    (r) =>
      '  { code: ' + J(r.code) + ', name: ' + J(r.name) +
      ', areaKm2: ' + r.areaKm2 + ', flagUrl: ' + J(r.flagUrl) + ' },'
  )
  .join(NL);

const out = [
  '// AUTO-GENERATED by scripts/gen-countries.mjs — do not edit by hand.',
  '// Source: world-countries (mledoze) + flagcdn.com (CORS-enabled SVG flags).',
  'export interface CountryInfo {',
  '  /** ISO 3166-1 alpha-2 code (uppercase). */',
  '  code: string;',
  '  /** Common English name. */',
  '  name: string;',
  '  /** Area in km² (the source exposes total area). */',
  '  areaKm2: number;',
  '  /** CORS-enabled SVG flag URL (flagcdn.com). */',
  '  flagUrl: string;',
  '}',
  '',
  'export const COUNTRIES: CountryInfo[] = [',
  entries,
  '];',
  '',
  'export const SIZE_OFFSET = ' + OFFSET + ';',
  'export const AREA_MAX_KM2 = ' + maxA + ';',
  'export const AREA_MIN_KM2 = ' + minA + ';',
  '',
  'const byCode = new Map(COUNTRIES.map((c) => [c.code, c]));',
  'export function findCountry(code: string | null | undefined): CountryInfo | undefined {',
  '  return code ? byCode.get(code.toUpperCase()) : undefined;',
  '}',
  '',
  '/**',
  " * Radius fraction of the viewport (of min(W,H)) derived from a country's area.",
  ' * size = (ln(areaKm2) + SIZE_OFFSET) / overallScale, normalized so the largest',
  ' * and smallest countries differ by exactly 2× (Russia ≈ 34.9, Vatican ≈ 17.5',
  ' * with the default overallScale of 200 → 17.5% / 8.7% of the viewport).',
  ' */',
  'export function countrySizeFraction(areaKm2: number, overallScale: number): number {',
  '  return (Math.log(areaKm2) + SIZE_OFFSET) / overallScale;',
  '}',
  '',
].join(NL);

fs.writeFileSync('src/lib/data/countries.ts', out);
console.log('wrote', rows.length, 'countries; offset =', OFFSET.toFixed(4));
console.log('Russia:', (Math.log(maxA) + OFFSET).toFixed(2), 'Vatican:', (Math.log(minA) + OFFSET).toFixed(2));
